"""Generate src-tauri/src/rawspeed_cameras.rs from rawspeed's data/cameras.xml.

darktable decodes RAWs with rawspeed, whose cameras.xml gives each camera's crop and colour
matrix. Emulsion decodes with LibRaw and uses this table where LibRaw lacks a camera.

Usage: python3 -I tools/rawspeed/generate.py <cameras.xml> <rawspeed commit> > src-tauri/src/rawspeed_cameras.rs
"""
import sys
import xml.etree.ElementTree as ET

path, commit = sys.argv[1], sys.argv[2]
rows, seen = [], set()
for cam in ET.parse(path).getroot().iter('Camera'):
    # The default mode only (not sRaw, compressed, 12-bit... variants), and supported cameras.
    if cam.get('mode') or cam.get('supported') == 'no':
        continue
    ident = cam.find('ID')
    make = ident.get('make') if ident is not None else cam.get('make')
    model = ident.get('model') if ident is not None else cam.get('model')
    makes = sorted({make, cam.get('make')})
    crop = cam.find('Crop')
    crop = tuple(int(crop.get(k)) for k in ('x', 'y', 'width', 'height')) if crop is not None else None
    matrix = None
    for m in cam.iter('ColorMatrix'):
        if m.get('planes') == '3':
            r = {int(row.get('plane')): [int(v) for v in row.text.split()] for row in m.iter('ColorMatrixRow')}
            if sorted(r) == [0, 1, 2] and all(len(v) == 3 for v in r.values()):
                matrix = [r[0], r[1], r[2]]
            break
    if crop is None and matrix is None:
        continue
    # Regional names for the same camera (EOS Rebel SL3, EOS Kiss X10 for the EOS 250D).
    models = [model] + [a.get('id') or a.text for a in cam.iter('Alias')]
    for name in dict.fromkeys(m for m in models if m):
        key = (tuple(makes), name)
        if key in seen:
            continue
        seen.add(key)
        rows.append((makes, name, crop, matrix))

def rust_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

print(f'''// Generated by tools/rawspeed/generate.py from rawspeed's data/cameras.xml at
// {commit} (https://github.com/darktable-org/rawspeed). Do not edit.
// The camera data is the rawspeed contributors' (Klaus Post and others), licensed CC-BY-SA 3.0
// (https://creativecommons.org/licenses/by-sa/3.0/); this table adapts it. See NOTICE.md.

/// A camera's crop (x, y, width, height; width or height ≤ 0 counts back from the edge) and
/// XYZ-to-camera matrix (× 10000), as darktable's decoder has them.
pub struct Camera {{
    pub makes: &'static [&'static str],
    pub model: &'static str,
    pub crop: Option<[i32; 4]>,
    pub matrix: Option<[[i32; 3]; 3]>,
}}

pub const CAMERAS: &[Camera] = &[''')
for makes, model, crop, matrix in rows:
    c = f'Some([{", ".join(map(str, crop))}])' if crop else 'None'
    m = 'Some([' + ', '.join('[' + ', '.join(map(str, r)) + ']' for r in matrix) + '])' if matrix else 'None'
    print(f'    Camera {{ makes: &[{", ".join(rust_str(x) for x in makes)}], model: {rust_str(model)}, crop: {c}, matrix: {m} }},')
print('];')
